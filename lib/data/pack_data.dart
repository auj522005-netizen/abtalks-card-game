  static QuestionPack _makePack(String id, String name, String desc, IconData icon, Color color, List<List<String>> questions) {
    final cards = <GameCard>[];
    for (final q in questions) {
      cards.add(GameCard(id: q[0], text: q[1], type: CardType.question, category: q[2], packId: id));
    }
    for (int i = 1; i <= 3; i++) {
      cards.add(GameCard(id: '${id}_free$i', text: 'حرية كاملة\nاطرح أي سؤال تريده', type: CardType.free, packId: id));
    }
    for (int i = 1; i <= 20; i++) {
      cards.add(GameCard(id: '${id}_ab$i', text: 'AB#', type: CardType.abHash, packId: id));
    }
    return QuestionPack(id: id, name: name, description: desc, icon: icon, color: color, cards: cards);
  }

